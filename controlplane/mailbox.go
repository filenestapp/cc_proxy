const (
	mailboxDomain        = "aifree.sg"
	mailboxWebmailURL    = "https://mail." + mailboxDomain
	mailboxRetention     = 30 * 24 * time.Hour
	mailboxRemoteTimeout = 45 * time.Second
	mailboxQuotaSQL      = `COALESCE((SELECT value::integer FROM settings WHERE key='mailbox_quota'),1)`
)

// $1 is the time shared by the paid-subscription check and its caller.
const mailboxPaidSQL = `EXISTS (SELECT 1 FROM subscriptions s WHERE s.customer_id=c.id
	AND s.status IN ('active','past_due') AND ` + subscriptionDeadlineSQL + ` > $1)`
const mailboxEligibleSQL = `(c.status='active' AND c.email_verified_at IS NOT NULL AND ` + mailboxPaidSQL + `)`

const mailboxSchemaSQL = `
CREATE TABLE IF NOT EXISTS mailboxes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers(id),
    address text NOT NULL,
    status text NOT NULL DEFAULT 'creating' CHECK (status IN ('creating','active','disabled','deleting','deleted')),
    cloudmail_user_id bigint CHECK (cloudmail_user_id > 0),
    remote_created boolean NOT NULL DEFAULT false,
    setup_pending boolean NOT NULL DEFAULT true,
    manually_disabled boolean NOT NULL DEFAULT false,
    status_sync_pending boolean NOT NULL DEFAULT false,
    created_at double precision NOT NULL,
    reclaim_at double precision,
    CHECK (status IN ('creating','deleted') OR cloudmail_user_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS mailbox_live_address ON mailboxes(address) WHERE status <> 'deleted';
CREATE UNIQUE INDEX IF NOT EXISTS mailbox_live_customer ON mailboxes(customer_id) WHERE status <> 'deleted';
CREATE UNIQUE INDEX IF NOT EXISTS mailbox_live_provider_user ON mailboxes(cloudmail_user_id) WHERE status <> 'deleted';
`

func ensureMailboxTables(ctx context.Context, db database) error {
	_, err := db.Exec(ctx, mailboxSchemaSQL)
	return err
}

type mailboxRecord struct {
	ID                int64    `json:"id"`
	CustomerID        int64    `json:"customer_id"`
	CustomerEmail     string   `json:"customer_email"`
	Address           string   `json:"address"`
	Status            string   `json:"status"`
	CloudMailUserID   *int64   `json:"-"`
	RemoteCreated     bool     `json:"-"`
	SetupPending      bool     `json:"setup_pending"`
	ManuallyDisabled  bool     `json:"-"`
	StatusSyncPending bool     `json:"-"`
	CreatedAt         float64  `json:"created_at"`
	ReclaimAt         *float64 `json:"reclaim_at"`
	Paid              bool     `json:"-"`
	Eligible          bool     `json:"entitled"`
}

const mailboxStateSQL = `SELECT m.*, c.email AS customer_email, entitlement.paid,
	(c.status='active' AND c.email_verified_at IS NOT NULL AND entitlement.paid) AS eligible
	FROM mailboxes m JOIN customers c ON c.id=m.customer_id
	CROSS JOIN LATERAL (SELECT ` + mailboxPaidSQL + ` AS paid) entitlement`

type customerMailboxView struct {
	Address    string `json:"address"`
	Status     string `json:"status"`
	WebmailURL string `json:"webmail_url"`
}

var mailboxLocalPart = regexp.MustCompile(`^[a-z0-9][a-z0-9.-]{1,30}[a-z0-9]$`)

func mailboxAddress(part string) (string, error) {
	part = strings.ToLower(strings.TrimSpace(part))
	reserved := []string{"admin", "noreply", "support", "postmaster", "abuse", "billing", "root"}
	if !mailboxLocalPart.MatchString(part) || strings.Contains(part, "..") || slices.Contains(reserved, part) {
		return "", failureCode(400, "invalid_local_part", "enter a valid, non-reserved mailbox name")
	}
	return part + "@" + mailboxDomain, nil
}

func mailboxUnavailable() error {
	return failureCode(502, "mail_unavailable", "the mail service is unavailable. Try again.")
}

func mailboxNoEntitlement() error {
	return failureCode(403, "no_entitlement", "an active, verified customer with a paid subscription is required")
}

// Serialize changes to one customer's mailboxes and billing entitlement across processes.
func lockMailboxCustomer(ctx context.Context, tx pgx.Tx, customerID int64) error {
	_, err := tx.Exec(ctx, `SELECT pg_advisory_xact_lock(67143004, hashtext(current_schema() || ':' || $1::bigint::text))`, customerID)
	return err
}

func (s *store) writeMailbox(ctx context.Context, customerID int64, change func(pgx.Tx) error) error {
	return pgx.BeginFunc(ctx, s.pool, func(tx pgx.Tx) error {
		if err := lockMailboxCustomer(ctx, tx, customerID); err != nil {
			return err
		}
		return change(tx)
	})
}

func getMailbox(ctx context.Context, db database, now float64, id int64) (mailboxRecord, error) {
	mailbox, err := rowOf[mailboxRecord](ctx, db, mailboxStateSQL+" WHERE m.id=$2", now, id)
	return mailbox, missing(err, "mailbox")
}

func saveMailbox(ctx context.Context, db database, m mailboxRecord) error {
	_, err := db.Exec(ctx, `UPDATE mailboxes SET status=$2,cloudmail_user_id=$3,remote_created=$4,
		setup_pending=$5,manually_disabled=$6,status_sync_pending=$7,reclaim_at=$8 WHERE id=$1`,
		m.ID, m.Status, m.CloudMailUserID, m.RemoteCreated, m.SetupPending, m.ManuallyDisabled, m.StatusSyncPending, m.ReclaimAt)
	return err
}

func (s *store) customerMailbox(ctx context.Context, customerID int64) (*customerMailboxView, error) {
	var mailbox customerMailboxView
	err := s.pool.QueryRow(ctx, `SELECT m.address,
		CASE WHEN m.status='active' AND NOT m.manually_disabled AND `+mailboxEligibleSQL+` THEN 'active' ELSE 'disabled' END
		FROM mailboxes m JOIN customers c ON c.id=m.customer_id
		WHERE m.customer_id=$2 AND NOT m.setup_pending AND m.status IN ('active','disabled','deleting')`, s.now(), customerID).
		Scan(&mailbox.Address, &mailbox.Status)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, nil
	}
	mailbox.WebmailURL = mailboxWebmailURL
	return &mailbox, err
}

func (s *store) reserveMailbox(ctx context.Context, customerID int64, address string) (int64, error) {
	var id int64
	err := s.writeMailbox(ctx, customerID, func(tx pgx.Tx) error {
		var eligible bool
		var quota int
		err := tx.QueryRow(ctx, `SELECT `+mailboxEligibleSQL+`, `+mailboxQuotaSQL+` FROM customers c WHERE c.id=$2`, s.now(), customerID).
			Scan(&eligible, &quota)
		if err != nil {
			return missing(err, "customer")
		}
		if !eligible {
			return mailboxNoEntitlement()
		}
		if quota <= 0 {
			return failureCode(409, "quota_exceeded", "the mailbox quota is zero")
		}
		if s.mailboxAdmin == nil {
			return mailboxUnavailable()
		}

		var existingAddress, status string
		var setupPending bool
		err = tx.QueryRow(ctx, `SELECT id,address,status,setup_pending FROM mailboxes
			WHERE customer_id=$1 AND status <> 'deleted'`, customerID).Scan(&id, &existingAddress, &status, &setupPending)
		if err == nil {
			if setupPending && existingAddress == address && status != "deleting" {
				return nil
			}
			return failureCode(409, "quota_exceeded", "this customer already has a mailbox")
		}
		if !errors.Is(err, pgx.ErrNoRows) {
			return err
		}
		err = tx.QueryRow(ctx, `INSERT INTO mailboxes(customer_id,address,created_at) VALUES($1,$2,$3)
			ON CONFLICT(address) WHERE status <> 'deleted' DO NOTHING RETURNING id`, customerID, address, s.now()).Scan(&id)
		if errors.Is(err, pgx.ErrNoRows) {
			return failureCode(409, "address_taken", "that mailbox address is already in use")
		}
		return err
	})
	return id, err
}

func (s *store) linkMailbox(ctx context.Context, m *mailboxRecord) error {
	if m.CloudMailUserID != nil {
		return nil
	}
	id, err := s.mailboxAdmin.findUser(ctx, m.Address)
	if err != nil {
		return mailboxUnavailable()
	}
	m.CloudMailUserID, m.Status = &id, "active"
	return nil
}

func (s *store) createMailbox(ctx context.Context, customerID int64, part string) (mailboxRecord, string, error) {
	address, err := mailboxAddress(part)
	if err != nil {
		return mailboxRecord{}, "", err
	}
	id, err := s.reserveMailbox(ctx, customerID, address)
	if err != nil {
		return mailboxRecord{}, "", err
	}
	var mailbox mailboxRecord
	var remoteErr error
	password := randomToken(24)
	err = s.writeMailbox(ctx, customerID, func(tx pgx.Tx) error {
		mailbox, err = getMailbox(ctx, tx, s.now(), id)
		if err != nil {
			return err
		}
		if !mailbox.Eligible {
			return mailboxNoEntitlement()
		}
		if !mailbox.SetupPending || mailbox.Status == "deleting" || mailbox.Status == "deleted" {
			return failureCode(409, "quota_exceeded", "this customer already has a mailbox")
		}
		remoteCtx, cancel := context.WithTimeout(ctx, mailboxRemoteTimeout)
		defer cancel()

		recovering := mailbox.RemoteCreated
		if !recovering {
			if err := s.mailboxAdmin.addUser(remoteCtx, address, password); err != nil {
				remoteErr = mailboxUnavailable()
				if errors.Is(err, errCloudMailAddressTaken) {
					remoteErr = failureCode(409, "address_taken", "that mailbox address is already in use")
				}
				_, err = tx.Exec(ctx, "DELETE FROM mailboxes WHERE id=$1", id)
				return err
			}
			mailbox.RemoteCreated = true
		}

		remoteErr = s.linkMailbox(remoteCtx, &mailbox)
		if remoteErr == nil && recovering {
			// A confirmed create can be resumed without keeping or reissuing its password.
			if err := s.mailboxAdmin.setPassword(remoteCtx, *mailbox.CloudMailUserID, password); err != nil {
				remoteErr = mailboxUnavailable()
			}
		}
		if remoteErr == nil {
			mailbox.SetupPending = false
		}
		return saveMailbox(ctx, tx, mailbox)
	})
	if err != nil {
		return mailboxRecord{}, "", err
	}
	if remoteErr != nil {
		return mailboxRecord{}, "", remoteErr
	}
	return mailbox, password, nil
}

type mailboxAction string

const (
	reconcileMailbox mailboxAction = ""
	disableMailbox   mailboxAction = "disable"
	enableMailbox    mailboxAction = "enable"
	deleteMailbox    mailboxAction = "delete"
)

func (m mailboxRecord) desiredDisabled() bool { return m.ManuallyDisabled || !m.Eligible }

func (m mailboxRecord) needsReconcile(now float64) bool {
	switch m.Status {
	case "deleting":
		return true
	case "creating":
		return m.RemoteCreated
	case "active", "disabled":
		return m.StatusSyncPending || (m.Status == "disabled") != m.desiredDisabled() ||
			(m.Paid && m.ReclaimAt != nil) || (!m.Paid && (m.ReclaimAt == nil || *m.ReclaimAt <= now))
	default:
		return false
	}
}

func (s *store) syncMailboxStatus(ctx context.Context, m *mailboxRecord) error {
	disabled := m.desiredDisabled()
	if m.StatusSyncPending || (m.Status == "disabled") != disabled {
		if err := s.mailboxAdmin.setStatus(ctx, *m.CloudMailUserID, disabled); err != nil {
			m.StatusSyncPending = true
			return mailboxUnavailable()
		}
		m.StatusSyncPending = false
		m.Status = "active"
		if disabled {
			m.Status = "disabled"
		}
	}
	return nil
}

func (s *store) changeMailbox(ctx context.Context, customerID, id int64, action mailboxAction, confirm string) error {
	var remoteErr error
	var deleting bool
	err := s.writeMailbox(ctx, customerID, func(tx pgx.Tx) error {
		m, err := getMailbox(ctx, tx, s.now(), id)
		if err != nil {
			return err
		}
		if action == deleteMailbox && m.Address != confirm {
			return failureCode(400, "invalid_confirmation", "enter the exact mailbox address to confirm deletion")
		}
		if m.Status == "deleted" {
			if action == deleteMailbox || action == reconcileMailbox {
				return nil
			}
			return missing(pgx.ErrNoRows, "mailbox")
		}
		if m.Status == "deleting" {
			if action == disableMailbox || action == enableMailbox {
				return failure(409, "this mailbox is being deleted")
			}
			deleting = true
			return nil
		}
		if action == enableMailbox && !m.Eligible {
			return mailboxNoEntitlement()
		}
		if !m.RemoteCreated {
			if action == deleteMailbox {
				m.Status = "deleted"
				return saveMailbox(ctx, tx, m)
			}
			if action == reconcileMailbox {
				return nil
			}
			return failure(409, "mailbox setup is incomplete")
		}
		if s.mailboxAdmin == nil {
			return mailboxUnavailable()
		}

		remoteCtx, cancel := context.WithTimeout(ctx, mailboxRemoteTimeout)
		defer cancel()
		if err := s.linkMailbox(remoteCtx, &m); err != nil {
			return err
		}
		switch action {
		case deleteMailbox:
			m.Status = "deleting"
		case disableMailbox:
			m.ManuallyDisabled = true
		case enableMailbox:
			m.ManuallyDisabled = false
		}
		if m.Status != "deleting" {
			remoteErr = s.syncMailboxStatus(remoteCtx, &m)
			if m.Paid {
				m.ReclaimAt = nil
			} else if remoteErr == nil {
				now := s.now()
				if m.ReclaimAt == nil {
					at := now + mailboxRetention.Seconds()
					m.ReclaimAt = &at
				} else if *m.ReclaimAt <= now {
					m.Status = "deleting"
				}
			}
		}
		deleting = m.Status == "deleting"
		return saveMailbox(ctx, tx, m)
	})
	if err != nil {
		return err
	}
	if remoteErr != nil {
		return remoteErr
	}
	if deleting {
		return s.finishMailboxDeletion(ctx, customerID, id)
	}
	return nil
}

func (s *store) finishMailboxDeletion(ctx context.Context, customerID, id int64) error {
	if s.mailboxAdmin == nil {
		return mailboxUnavailable()
	}
	return s.writeMailbox(ctx, customerID, func(tx pgx.Tx) error {
		m, err := getMailbox(ctx, tx, s.now(), id)
		if err != nil || m.Status != "deleting" {
			return err
		}
		remoteCtx, cancel := context.WithTimeout(ctx, mailboxRemoteTimeout)
		defer cancel()
		// Disable sign-in and revoke sessions before permanently deleting the user.
		if err := s.mailboxAdmin.setStatus(remoteCtx, *m.CloudMailUserID, true); err != nil {
			return mailboxUnavailable()
		}
		if err := s.mailboxAdmin.deleteUser(remoteCtx, *m.CloudMailUserID); err != nil {
			return mailboxUnavailable()
		}
		m.Status, m.ReclaimAt = "deleted", nil
		return saveMailbox(ctx, tx, m)
	})
}

func (s *store) reconcileMailboxes(ctx context.Context) error {
	if s.mailboxAdmin == nil {
		return nil
	}
	now := s.now()
	mailboxes, err := rowsOf[mailboxRecord](ctx, s.pool, mailboxStateSQL+" WHERE m.status <> 'deleted' ORDER BY m.id", now)
	if err != nil {
		return err
	}
	var failures []error
	for _, m := range mailboxes {
		if ctx.Err() != nil {
			return ctx.Err()
		}
		if m.needsReconcile(now) {
			if err := s.changeMailbox(ctx, m.CustomerID, m.ID, reconcileMailbox, ""); err != nil {
				failures = append(failures, fmt.Errorf("mailbox %d: %w", m.ID, err))
			}
		}
	}
	return errors.Join(failures...)
}

func (s *store) runMailboxLifecycle(ctx context.Context) {
	if s.mailboxAdmin == nil {
		return
	}
	ticker := time.NewTicker(time.Minute)
	defer ticker.Stop()
	for {
		if err := s.reconcileMailboxes(ctx); err != nil && ctx.Err() == nil {
			log.Printf("reconcile mailboxes: %v", err)
		}
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
		}
	}
}

func (a *api) mailboxAdminRoutes() {
	a.bind("POST /admin/customers/{id}/mailbox", "admin", "mailbox_create", a.adminMailboxCreate)
	a.bind("GET /admin/mailboxes", "admin", "", a.adminMailboxes)
	a.bind("POST /admin/mailboxes/{id}/disable", "admin", "mailbox_disable", a.adminMailboxChange(disableMailbox))
	a.bind("POST /admin/mailboxes/{id}/enable", "admin", "mailbox_enable", a.adminMailboxChange(enableMailbox))
	a.bindWithBody("DELETE /admin/mailboxes/{id}", "admin", "mailbox_delete", a.adminMailboxChange(deleteMailbox), true)
}

func (a *api) adminMailboxCreate(r *apiRequest) (response, error) {
	var body struct {
		LocalPart string `json:"local_part"`
	}
	if err := r.decode(&body); err != nil {
		return response{}, failureCode(400, "invalid_local_part", "enter a valid mailbox name")
	}
	id, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
	if err != nil || id <= 0 {
		return response{}, failure(400, "invalid customer ID")
	}
	mailbox, password, err := a.store.createMailbox(r.Context(), id, body.LocalPart)
	return created(object{"mailbox": mailbox, "initial_password": password}, err)
}

func (a *api) adminMailboxes(r *apiRequest) (response, error) {
	return ok(rowsOf[mailboxRecord](r.Context(), a.store.pool, mailboxStateSQL+" ORDER BY m.id DESC", a.store.now()))
}

func (a *api) adminMailboxChange(action mailboxAction) endpoint {
	return func(r *apiRequest) (response, error) {
		id, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
		if err != nil || id <= 0 {
			return response{}, failure(400, "invalid mailbox ID")
		}
		var body struct {
			Confirm string `json:"confirm"`
		}
		if action == deleteMailbox {
			if err := r.decode(&body); err != nil {
				return response{}, failureCode(400, "invalid_confirmation", "enter the exact mailbox address to confirm deletion")
			}
		}
		var customerID int64
		err = a.store.pool.QueryRow(r.Context(), "SELECT customer_id FROM mailboxes WHERE id=$1", id).Scan(&customerID)
		if err != nil {
			return response{}, missing(err, "mailbox")
		}
		err = a.store.changeMailbox(r.Context(), customerID, id, action, body.Confirm)
		return response{status: http.StatusNoContent}, err
	}
}
