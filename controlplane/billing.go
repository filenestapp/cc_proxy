func (a *api) accountCheckout(r *apiRequest) (response, error) {
	if a.store.stripe == nil || stripeWebhookSecret() == "" {
		return response{}, failureCode(503, "stripe_unavailable", "Stripe Checkout is not configured")
	}
	var body struct {
		Plan string `json:"plan"`
	}
	if err := r.decode(&body, "plan"); err != nil {
		return response{}, err
	}
	ctx := r.Context()
	customer, err := a.store.customerByID(ctx, r.Customer.CustomerID)
	if err != nil {
		return response{}, err
	}
	if !customer.EmailVerified {
		return response{}, failureCode(403, "email_unverified", "email is not verified")
	}
	reservation, err := a.store.reserveCheckout(ctx, customer.ID, body.Plan)
	var change *pendingCheckoutPlanChange
	if err != nil && !errors.As(err, &change) {
		return response{}, err
	}
	stripeCustomer, err := a.store.customerStripeID(ctx, customer.ID)
	if err != nil {
		return response{}, err
	}
	if stripeCustomer == "" {
		key := fmt.Sprintf("aifree-customer-%d-%.6f-%s", customer.ID, customer.CreatedAt, hashToken(customer.Email))
		stripeCustomer, err = a.store.stripe.createCustomer(ctx, customer.Email, key)
		if err != nil {
			return response{}, err
		}
		stripeCustomer, err = a.store.setCustomerStripeID(ctx, customer.ID, stripeCustomer)
		if err != nil {
			return response{}, err
		}
	}
	if change != nil {
		if change.sessionID == "" {
			previous, err := a.submitCheckout(ctx, stripeCustomer, change.reservation)
			// Legacy reservations lack a request marker. An immutable Price mismatch means their validation could never pass.
			if err != nil && !(change.legacy && errors.Is(err, errStripeCheckoutPriceMismatch)) {
				return response{}, err
			}
			change.sessionID = previous.ID
		}
		if change.sessionID != "" {
			if err := a.store.stripe.expireCheckout(ctx, change.sessionID); err != nil {
				if errors.Is(err, errStripeCheckoutCompleted) {
					return response{}, failureCode(409, "subscription_exists", "a subscription or Checkout Session already exists")
				}
				return response{}, err
			}
		}
		reservation, err = a.store.replacePendingCheckout(ctx, *change, body.Plan)
		if err != nil {
			return response{}, err
		}
	}
	checkout, err := a.submitCheckout(ctx, stripeCustomer, reservation)
	if err != nil {
		return response{}, err
	}
	if err := a.store.setCheckoutSessionID(ctx, reservation.ID, checkout.ID); err != nil {
		return response{}, err
	}
	return ok(object{"url": checkout.URL}, nil)
}

func (a *api) submitCheckout(ctx context.Context, stripeCustomer string, reservation checkoutReservation) (stripeCheckoutSession, error) {
	if err := a.store.stripe.validateCheckoutPrice(ctx, reservation); err != nil {
		return stripeCheckoutSession{}, err
	}
	if err := a.store.startCheckoutRequest(ctx, reservation.ID); err != nil {
		return stripeCheckoutSession{}, err
	}
	return a.store.stripe.createCheckout(ctx, stripeCustomer, reservation)
}

