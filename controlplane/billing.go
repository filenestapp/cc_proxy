func (s *store) completeProvisioning(ctx context.Context, id int64, note string) error {
	return s.write(ctx, func(tx pgx.Tx) error {
		var kind string
		var subscriptionID int64
		if err := tx.QueryRow(ctx, `UPDATE provisioning p SET status='done',note=$2,done_at=$3 FROM subscriptions s
			WHERE p.id=$1 AND p.status='todo' AND s.id=p.subscription_id AND s.status IN ('active','past_due')
			AND (p.kind <> 'team_seat' OR s.plan_code IN ('standard','premium')) RETURNING p.kind,p.subscription_id`, id, note, s.now()).Scan(&kind, &subscriptionID); err != nil {
			return missing(err, "provisioning item")
		}
		if kind == "waiting_ip" {
			if err := s.provisionSubscription(ctx, tx, subscriptionID); err != nil {
				return err
			}
			var state string
			if err := tx.QueryRow(ctx, `SELECT state FROM customer_proxy WHERE customer_id=(SELECT customer_id FROM subscriptions WHERE id=$1)`, subscriptionID).Scan(&state); err != nil {
				return err
			}
			if state != "ready" {
				return failure(409, "no free IP is available")
			}
		}
		return nil
	})
}

