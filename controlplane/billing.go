const billingSchemaSQL = `
CREATE TABLE IF NOT EXISTS plans (
    code text PRIMARY KEY CHECK (code IN ('standard', 'premium', 'residential_ip')),
    name text NOT NULL, price_cny integer NOT NULL CHECK (price_cny > 0),
    currency text NOT NULL DEFAULT 'cny', interval text NOT NULL DEFAULT 'month',
    fulfillment text NOT NULL CHECK (fulfillment IN ('manual', 'auto_ip')),
    stripe_price_id text NOT NULL DEFAULT '', active boolean NOT NULL DEFAULT true, sort integer NOT NULL
);
INSERT INTO plans(code,name,price_cny,fulfillment,sort) VALUES
 ('standard','Standard',60000,'manual',10),
 ('premium','Premium',150000,'manual',20),
 ('residential_ip','海外住宅 IP',40000,'auto_ip',30)
ON CONFLICT (code) DO NOTHING;
CREATE TABLE IF NOT EXISTS subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    plan_code text NOT NULL REFERENCES plans(code), stripe_subscription_id text UNIQUE,
    status text NOT NULL CHECK (status IN ('pending','active','past_due','cancelled','expired')),
    current_period_start double precision, current_period_end double precision,
    cancel_at_period_end boolean NOT NULL DEFAULT false, event_created double precision NOT NULL DEFAULT 0,
    created_at double precision NOT NULL, updated_at double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS subscriptions_customer ON subscriptions(customer_id, updated_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS subscriptions_open_customer ON subscriptions(customer_id)
 WHERE status IN ('pending','active','past_due');
CREATE TABLE IF NOT EXISTS orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id bigint NOT NULL REFERENCES customers(id),
    subscription_id bigint REFERENCES subscriptions(id), amount_cny integer NOT NULL, currency text NOT NULL DEFAULT 'cny',
    provider text NOT NULL DEFAULT 'stripe', provider_ref text UNIQUE, status text NOT NULL CHECK (status IN ('pending','paid','failed','refunded')),
    receipt_url text NOT NULL DEFAULT '', paid_at double precision, created_at double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS orders_customer ON orders(customer_id, created_at DESC);
CREATE TABLE IF NOT EXISTS stripe_events (
    event_id text PRIMARY KEY, type text NOT NULL, object_id text NOT NULL DEFAULT '', object_created double precision NOT NULL DEFAULT 0,
    received_at double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS customer_proxy (
    customer_id bigint PRIMARY KEY REFERENCES customers(id) ON DELETE CASCADE,
    user_name text NOT NULL UNIQUE REFERENCES users(name), state text NOT NULL CHECK (state IN ('ready','waiting_ip','none')),
    created_at double precision NOT NULL, updated_at double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS provisioning (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    subscription_id bigint NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
    kind text NOT NULL CHECK (kind IN ('team_seat','waiting_ip','mailbox')),
    status text NOT NULL DEFAULT 'todo' CHECK (status IN ('todo','done')), note text NOT NULL DEFAULT '',
    created_at double precision NOT NULL, done_at double precision
);
CREATE UNIQUE INDEX IF NOT EXISTS provisioning_open ON provisioning(subscription_id, kind) WHERE status = 'todo';
INSERT INTO settings(key, value) VALUES ('subscription_grace_seconds', '259200') ON CONFLICT (key) DO NOTHING;
`

func ensureBillingTables(ctx context.Context, db database) error {
	_, err := db.Exec(ctx, billingSchemaSQL)
	return err
}

