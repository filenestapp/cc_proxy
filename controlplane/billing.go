func (s *store) loginCustomerProxy(ctx context.Context, customerID int64, device, platform string) (string, userSummary, error) {
	var name string
	var entitled bool
	err := s.pool.QueryRow(ctx, `SELECT cp.user_name, EXISTS(SELECT 1 FROM subscriptions s WHERE s.customer_id=$1 AND s.status IN ('active','past_due') AND (s.current_period_end IS NULL OR s.current_period_end + COALESCE((SELECT value::double precision FROM settings WHERE key='subscription_grace_seconds'),259200) > $2)) FROM customer_proxy cp WHERE cp.customer_id=$1`, customerID, s.now()).Scan(&name, &entitled)
	if errors.Is(err, pgx.ErrNoRows) || !entitled {
		return "", userSummary{}, failureCode(403, "no_active_subscription", "no active subscription")
	}
	if err != nil {
		return "", userSummary{}, err
	}
	token, err := s.addDevice(ctx, name, device, truncate(platform, 32))
	if err != nil {
		return "", userSummary{}, err
	}
	user, err := userInfo(ctx, s.pool, name)
	return token, user, err
}
