func (s *store) updatePlans(ctx context.Context, plans []planView) error {
	return s.write(ctx, func(tx pgx.Tx) error {
		for _, p := range plans {
			if p.Amount < 1 || strings.TrimSpace(p.Name) == "" {
				return failure(400, "invalid plan")
			}
			tag, err := tx.Exec(ctx, `UPDATE plans SET name=$2,price_cny=$3,stripe_price_id=$4,active=$5,sort=$6 WHERE code=$1`, p.Code, strings.TrimSpace(p.Name), p.Amount, strings.TrimSpace(p.StripePriceID), p.Active, p.Sort)
			if err := rowsChanged(tag, err, "plan "+p.Code); err != nil {
				return err
			}
		}
		var duplicatePrice bool
		if err := tx.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM plans WHERE stripe_price_id <> '' GROUP BY stripe_price_id HAVING count(*) > 1)`).Scan(&duplicatePrice); err != nil {
			return err
		}
		if duplicatePrice {
			return failure(400, "assign a different Stripe Price ID to each plan")
		}
		return nil
	})
}

func (s *store) customerEntitlement(ctx context.Context, customerID int64) (*subscriptionView, any, error) {
	sub, err := rowOf[subscriptionView](ctx, s.pool, `SELECT s.id,s.plan_code AS plan,s.status,s.current_period_start,s.current_period_end,s.cancel_at_period_end,
	(SELECT status FROM provisioning WHERE subscription_id=s.id AND kind='team_seat' AND s.plan_code IN ('standard','premium') ORDER BY id DESC LIMIT 1) AS team_seat
	FROM subscriptions s WHERE s.customer_id=$1 AND s.stripe_subscription_id IS NOT NULL
	ORDER BY (s.status IN ('pending','active','past_due')) DESC, s.created_at DESC, s.id DESC LIMIT 1`, customerID)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, nil, nil
	}
	if err != nil {
		return nil, nil, err
	}
	var proxy proxyView
	err = s.pool.QueryRow(ctx, `SELECT CASE WHEN u.egress_ip IS NOT NULL THEN 'ready' WHEN cp.state='ready' THEN 'waiting_ip' ELSE cp.state END,host(u.egress_ip)
		FROM customer_proxy cp JOIN users u ON u.name=cp.user_name WHERE cp.customer_id=$1`, customerID).Scan(&proxy.State, &proxy.EgressIP)
	if errors.Is(err, pgx.ErrNoRows) {
		sub.Proxy = proxyView{State: "none"}
		return &sub, nil, nil
	}
	if err != nil {
		return nil, nil, err
	}
	sub.Proxy = proxy
	return &sub, proxy, nil
}
func (s *store) currentSubscription(ctx context.Context, customerID int64) (*subscriptionView, error) {
	sub, _, err := s.customerEntitlement(ctx, customerID)
	return sub, err
}
