func stripeTimestamp(value int64) *float64 {
	if value == 0 {
		return nil
	}
	seconds := float64(value)
	return &seconds
}

func (s stripeSubscription) Start() *float64 {
	if len(s.Items.Data) > 0 && s.Items.Data[0].CurrentPeriodStart != 0 {
		return stripeTimestamp(s.Items.Data[0].CurrentPeriodStart)
	}
	return stripeTimestamp(s.CurrentPeriodStart)
}

func (s stripeSubscription) End() *float64 {
	if len(s.Items.Data) > 0 && s.Items.Data[0].CurrentPeriodEnd != 0 {
		return stripeTimestamp(s.Items.Data[0].CurrentPeriodEnd)
	}
	return stripeTimestamp(s.CurrentPeriodEnd)
}

func (s stripeSubscription) PriceID() string {
	if len(s.Items.Data) == 0 {
		return ""
	}
	return s.Items.Data[0].Price.ID
}

