var errStripeCheckoutCompleted = errors.New("Stripe Checkout Session already completed")
var errStripeCheckoutPriceMismatch = failureCode(503, "stripe_unavailable", checkoutPriceErrorMessage)

const (
	stripeAPIVersion          = "2026-11-18.endive"
	accountURL                = "https://app.aifree.sg/account"
	checkoutPriceErrorMessage = "Stripe Price must match the active monthly CNY plan"
)

type stripeHTTPClient struct {
	key    string
	client *http.Client
}

func newStripeClientFromEnv() stripeClient {
	if key := strings.TrimSpace(os.Getenv("STRIPE_SECRET_KEY")); key != "" {
		return &stripeHTTPClient{key: key, client: &http.Client{Timeout: 15 * time.Second}}
	}
	return nil
}

func stripeWebhookSecret() string {
	return strings.TrimSpace(os.Getenv("STRIPE_WEBHOOK_SECRET"))
}

func (c *stripeHTTPClient) call(ctx context.Context, method, path string, values url.Values, key string, out any) error {
	endpoint := "https://api.stripe.com/v1" + path
	if method == http.MethodGet {
		endpoint += "?" + values.Encode()
	}
	var body io.Reader
	if method == http.MethodPost {
		body = strings.NewReader(values.Encode())
	}
	req, err := http.NewRequestWithContext(ctx, method, endpoint, body)
	if err != nil {
		return err
	}
	req.SetBasicAuth(c.key, "")
	req.Header.Set("Stripe-Version", stripeAPIVersion)
	if body != nil {
		req.Header.Set("Content-Type", "application/x-www-form-urlencoded")
	}
	if key != "" {
		req.Header.Set("Idempotency-Key", key)
	}
	res, err := c.client.Do(req)
	if err != nil {
		return err
	}
	defer res.Body.Close()
	if res.StatusCode/100 != 2 {
		return fmt.Errorf("Stripe %s %s returned HTTP %d", method, path, res.StatusCode)
	}
	return json.NewDecoder(io.LimitReader(res.Body, 1<<20)).Decode(out)
}

func (c *stripeHTTPClient) createCustomer(ctx context.Context, email, key string) (string, error) {
	var result struct{ ID string }
	err := c.call(ctx, http.MethodPost, "/customers", url.Values{"email": {email}}, key, &result)
	if err == nil && result.ID == "" {
		err = errors.New("Stripe customer response missing ID")
	}
	return result.ID, err
}

func (c *stripeHTTPClient) validateCheckoutPrice(ctx context.Context, reservation checkoutReservation) error {
	var price struct {
		Active     bool
		Currency   string
		UnitAmount int `json:"unit_amount"`
		Recurring  struct {
			Interval      string
			IntervalCount int `json:"interval_count"`
		}
	}
	if err := c.call(ctx, http.MethodGet, "/prices/"+url.PathEscape(reservation.PriceID), nil, "", &price); err != nil {
		return err
	}
	if price.Currency != "cny" || price.UnitAmount != reservation.Amount || price.Recurring.Interval != "month" || price.Recurring.IntervalCount != 1 {
		return errStripeCheckoutPriceMismatch
	}
	if !price.Active {
		return failureCode(503, "stripe_unavailable", checkoutPriceErrorMessage)
	}
	return nil
}

func (c *stripeHTTPClient) createCheckout(ctx context.Context, customer string, reservation checkoutReservation) (stripeCheckoutSession, error) {
	id := strconv.FormatInt(reservation.ID, 10)
	values := url.Values{
		"mode": {"subscription"}, "customer": {customer}, "line_items[0][price]": {reservation.PriceID},
		"line_items[0][quantity]": {"1"}, "client_reference_id": {strconv.FormatInt(reservation.CustomerID, 10)},
		"success_url": {accountURL + "?checkout=success"}, "cancel_url": {accountURL + "?checkout=cancel"},
		"expires_at": {strconv.FormatInt(reservation.ExpiresAt, 10)}, "integration_identifier": {"aifree-checkout-kjsmqpuz"},
		"metadata[plan]": {reservation.Plan}, "metadata[aifree_subscription_id]": {id},
		"subscription_data[metadata][aifree_subscription_id]": {id},
	}
	var result stripeCheckoutSession
	err := c.call(ctx, http.MethodPost, "/checkout/sessions", values, "aifree-checkout-"+customer+"-"+id, &result)
	if err == nil && (result.ID == "" || result.URL == "") {
		err = errors.New("Stripe Checkout response missing ID or URL")
	}
	return result, err
}

func (c *stripeHTTPClient) expireCheckout(ctx context.Context, sessionID string) error {
	path := "/checkout/sessions/" + url.PathEscape(sessionID)
	var session struct{ ID, Status string }
	expireErr := c.call(ctx, http.MethodPost, path+"/expire", nil, "", &session)
	if expireErr != nil {
		// Stripe rejects expiry for both completed and expired Sessions. A read also resolves a lost response.
		if err := c.call(ctx, http.MethodGet, path, nil, "", &session); err != nil {
			return expireErr
		}
	}
	if session.ID != sessionID {
		return errors.New("Stripe Checkout Session ID did not match")
	}
	switch session.Status {
	case "expired":
		return nil
	case "complete":
		return errStripeCheckoutCompleted
	}
	if expireErr != nil {
		return expireErr
	}
	return errors.New("Stripe Checkout Session expiration was not confirmed")
}

func (c *stripeHTTPClient) createPortal(ctx context.Context, customer, returnURL string) (string, error) {
	var result struct{ URL string }
	err := c.call(ctx, http.MethodPost, "/billing_portal/sessions", url.Values{"customer": {customer}, "return_url": {returnURL}}, "", &result)
	if err == nil && result.URL == "" {
		err = errors.New("Stripe portal response missing URL")
	}
	return result.URL, err
}

func (c *stripeHTTPClient) getSubscription(ctx context.Context, id string) (stripeSubscription, error) {
	var result stripeSubscription
	err := c.call(ctx, http.MethodGet, "/subscriptions/"+url.PathEscape(id), url.Values{"expand[]": {"latest_invoice"}}, "", &result)
	return result, err
}

