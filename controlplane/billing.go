func (s *store) loginCustomerProxy(ctx context.Context, customerID int64, device, platform string) (string, userSummary, error) {
	token := randomToken(32)
	var summary userSummary
	err := s.mutate(ctx, func(tx pgx.Tx) error {
		var name string
		err := tx.QueryRow(ctx, `SELECT cp.user_name FROM customer_proxy cp JOIN customers c ON c.id=cp.customer_id
			JOIN users u ON u.name=cp.user_name WHERE c.id=$1 AND c.status='active' AND u.egress_ip IS NOT NULL
			AND EXISTS (SELECT 1 FROM subscriptions s WHERE s.customer_id=c.id AND s.status IN ('active','past_due')
			AND `+subscriptionDeadlineSQL+` > $2)`, customerID, s.now()).Scan(&name)
		if errors.Is(err, pgx.ErrNoRows) {
			return failureCode(403, "no_active_subscription", "no active subscription with an assigned IP")
		}
		if err != nil {
			return err
		}
		user, err := getUser(ctx, tx, name)
		if err != nil {
			return err
		}
		if err := s.putDevice(ctx, tx, user, device, truncate(platform, 32), token); err != nil {
			return err
		}
		summary, err = userInfo(ctx, tx, name)
		return err
	})
	return token, summary, err
}

