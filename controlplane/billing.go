func (s *store) storeStripeEvent(ctx context.Context, event stripeEvent) error {
	return s.write(ctx, func(tx pgx.Tx) error {
		var stored string
		err := tx.QueryRow(ctx, `INSERT INTO stripe_events(event_id,type,object_id,object_created,received_at) VALUES($1,$2,$3,$4,$5) ON CONFLICT DO NOTHING RETURNING event_id`, event.ID, event.Type, event.ObjectID(), float64(event.Created), s.now()).Scan(&stored)
		if errors.Is(err, pgx.ErrNoRows) {
			return nil
		}
		if err != nil {
			return err
		}
		return s.applyStripeEvent(ctx, tx, event)
	})
}

func (s *store) applyStripeEvent(ctx context.Context, tx pgx.Tx, event stripeEvent) error {
	switch event.Type {
	case "checkout.session.completed":
		var session stripeCheckout
		if err := json.Unmarshal(event.Data.Object, &session); err != nil {
			return err
		}
		customerID, err := strconv.ParseInt(session.ClientReferenceID, 10, 64)
		if err != nil {
			return nil
		}
		plan := session.Metadata["plan"]
		if plan == "" {
			return nil
		}
		if session.Customer != "" {
			if _, err := tx.Exec(ctx, "UPDATE customers SET stripe_customer_id=COALESCE(stripe_customer_id,$2) WHERE id=$1", customerID, session.Customer); err != nil {
				return err
			}
		}
		subID, err := s.upsertSubscription(ctx, tx, customerID, plan, session.Subscription, "pending", nil, nil, false, float64(event.Created))
		if err != nil {
			return err
		}
		_, err = tx.Exec(ctx, `INSERT INTO orders(customer_id,subscription_id,amount_cny,provider_ref,status,created_at) VALUES($1,$2,$3,$4,'pending',$5) ON CONFLICT(provider_ref) DO NOTHING`, customerID, subID, session.AmountTotal, session.ID, s.now())
		return err
	case "customer.subscription.created", "customer.subscription.updated", "customer.subscription.deleted":
		var sub stripeSubscription
		if err := json.Unmarshal(event.Data.Object, &sub); err != nil {
			return err
		}
		return s.applySubscription(ctx, tx, sub, event.Created, event.Type == "customer.subscription.deleted")
	case "invoice.paid", "invoice.payment_failed":
		var invoice stripeInvoice
		if err := json.Unmarshal(event.Data.Object, &invoice); err != nil {
			return err
		}
		status := "paid"
		subscriptionStatus := "active"
		if event.Type == "invoice.payment_failed" {
			status = "failed"
			subscriptionStatus = "past_due"
		}
		var customerID int64
		var subID *int64
		err := tx.QueryRow(ctx, "SELECT customer_id,id FROM subscriptions WHERE stripe_subscription_id=$1", invoice.Subscription).Scan(&customerID, &subID)
		if errors.Is(err, pgx.ErrNoRows) {
			return nil
		}
		if err != nil {
			return err
		}
		_, err = tx.Exec(ctx, `INSERT INTO orders(customer_id,subscription_id,amount_cny,provider_ref,status,receipt_url,paid_at,created_at) VALUES($1,$2,$3,$4,$5,$6,CASE WHEN $5='paid' THEN $7 END,$7) ON CONFLICT(provider_ref) DO UPDATE SET status=EXCLUDED.status,receipt_url=EXCLUDED.receipt_url,paid_at=EXCLUDED.paid_at`, customerID, *subID, invoice.AmountPaid, invoice.ID, status, invoice.HostedInvoiceURL, s.now())
		if err != nil {
			return err
		}
		updated, err := tx.Exec(ctx, `UPDATE subscriptions SET status=$2,updated_at=$3,event_created=$4 WHERE id=$1 AND status != 'cancelled' AND event_created <= $4`, *subID, subscriptionStatus, s.now(), float64(event.Created))
		if err != nil {
			return err
		}
		if subscriptionStatus == "active" && updated.RowsAffected() != 0 {
			return s.provisionSubscription(ctx, tx, *subID)
		}
		return nil
	}
	return nil
}

func (s *store) applySubscription(ctx context.Context, tx pgx.Tx, source stripeSubscription, created int64, deleted bool) error {
	customerID, err := s.customerByStripeID(ctx, tx, source.Customer)
	if err != nil {
		return err
	}
	plan, err := s.planForStripe(ctx, tx, source)
	if err != nil {
		return err
	}
	status := stripeSubscriptionStatus(source.Status, deleted)
	id, err := s.upsertSubscription(ctx, tx, customerID, plan, source.ID, status, source.Start(), source.End(), source.CancelAtPeriodEnd, float64(created))
	if err != nil {
		return err
	}
	if status == "active" {
		return s.provisionSubscription(ctx, tx, id)
	}
	if status == "cancelled" {
		return s.deprovisionSubscription(ctx, tx, id)
	}
	return nil
}
func (s *store) customerByStripeID(ctx context.Context, db database, id string) (int64, error) {
	var customerID int64
	err := db.QueryRow(ctx, "SELECT id FROM customers WHERE stripe_customer_id=$1", id).Scan(&customerID)
	return customerID, err
}
func (s *store) planForStripe(ctx context.Context, db database, sub stripeSubscription) (string, error) {
	if p := sub.Metadata["plan"]; p != "" {
		return p, nil
	}
	var plan string
	err := db.QueryRow(ctx, "SELECT code FROM plans WHERE stripe_price_id=$1", sub.PriceID()).Scan(&plan)
	return plan, err
}
func stripeSubscriptionStatus(value string, deleted bool) string {
	if deleted || value == "canceled" || value == "unpaid" {
		return "cancelled"
	}
	if value == "past_due" {
		return "past_due"
	}
	if value == "active" || value == "trialing" {
		return "active"
	}
	return "pending"
}
func (s *store) upsertSubscription(ctx context.Context, tx pgx.Tx, customerID int64, plan, stripeID, status string, start, end *float64, cancel bool, eventCreated float64) (int64, error) {
	var id int64
	err := tx.QueryRow(ctx, `INSERT INTO subscriptions(customer_id,plan_code,stripe_subscription_id,status,current_period_start,current_period_end,cancel_at_period_end,event_created,created_at,updated_at) VALUES($1,$2,NULLIF($3,''),$4,$5,$6,$7,$8,$9,$9) ON CONFLICT(stripe_subscription_id) DO UPDATE SET plan_code=EXCLUDED.plan_code,status=EXCLUDED.status,current_period_start=EXCLUDED.current_period_start,current_period_end=EXCLUDED.current_period_end,cancel_at_period_end=EXCLUDED.cancel_at_period_end,event_created=EXCLUDED.event_created,updated_at=EXCLUDED.updated_at WHERE subscriptions.event_created <= EXCLUDED.event_created RETURNING id`, customerID, plan, stripeID, status, start, end, cancel, eventCreated, s.now()).Scan(&id)
	if errors.Is(err, pgx.ErrNoRows) {
		err = tx.QueryRow(ctx, "SELECT id FROM subscriptions WHERE stripe_subscription_id=$1", stripeID).Scan(&id)
	}
	return id, err
}
func (s *store) provisionSubscription(ctx context.Context, tx pgx.Tx, subscriptionID int64) error {
	var customerID int64
	var plan string
	err := tx.QueryRow(ctx, "SELECT customer_id,plan_code FROM subscriptions WHERE id=$1", subscriptionID).Scan(&customerID, &plan)
	if err != nil {
		return err
	}
	var user string
	err = tx.QueryRow(ctx, "SELECT user_name FROM customer_proxy WHERE customer_id=$1", customerID).Scan(&user)
	if errors.Is(err, pgx.ErrNoRows) {
		user = "c" + strconv.FormatInt(customerID, 10)
		_, err = tx.Exec(ctx, "INSERT INTO users(name,password_hash,mode,max_devices,created_at) VALUES($1,$2,'exclusive',$3,$4)", user, hashPassword(randomToken(32)), maxDevices, s.now())
		if err != nil {
			return err
		}
		_, err = tx.Exec(ctx, "INSERT INTO customer_proxy(customer_id,user_name,state,created_at,updated_at) VALUES($1,$2,'none',$3,$3)", customerID, user, s.now())
		if err != nil {
			return err
		}
	} else if err != nil {
		return err
	}
	u, err := getUser(ctx, tx, user)
	if err != nil {
		return err
	}
	if u.IP == nil {
		ip, h, port, assignErr := s.chooseBinding(ctx, tx, u, assignment{})
		if assignErr != nil {
			_, err = tx.Exec(ctx, "UPDATE customer_proxy SET state='waiting_ip',updated_at=$2 WHERE customer_id=$1", customerID, s.now())
			if err != nil {
				return err
			}
			_, err = tx.Exec(ctx, `INSERT INTO provisioning(customer_id,subscription_id,kind,created_at) VALUES($1,$2,'waiting_ip',$3) ON CONFLICT DO NOTHING`, customerID, subscriptionID, s.now())
			return err
		}
		if _, err = tx.Exec(ctx, "UPDATE users SET egress_ip=$2::text::inet,host=$3,port=$4 WHERE name=$1", user, ip, h.Name, port); err != nil {
			return err
		}
	}
	if _, err = tx.Exec(ctx, "UPDATE customer_proxy SET state='ready',updated_at=$2 WHERE customer_id=$1", customerID, s.now()); err != nil {
		return err
	}
	if plan == "standard" || plan == "premium" {
		_, err = tx.Exec(ctx, `INSERT INTO provisioning(customer_id,subscription_id,kind,created_at) VALUES($1,$2,'team_seat',$3) ON CONFLICT DO NOTHING`, customerID, subscriptionID, s.now())
	}
	return err
}
func (s *store) deprovisionSubscription(ctx context.Context, tx pgx.Tx, subscriptionID int64) error {
	var customerID int64
	err := tx.QueryRow(ctx, "SELECT customer_id FROM subscriptions WHERE id=$1", subscriptionID).Scan(&customerID)
	if err != nil {
		return err
	}
	var user string
	err = tx.QueryRow(ctx, "SELECT user_name FROM customer_proxy WHERE customer_id=$1", customerID).Scan(&user)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil
	}
	if err != nil {
		return err
	}
	u, err := getUser(ctx, tx, user)
	if err != nil {
		return err
	}
	if _, err = tx.Exec(ctx, "UPDATE devices SET revoked_at=$2 WHERE user_name=$1 AND revoked_at IS NULL", user, s.now()); err != nil {
		return err
	}
	if err = s.releaseBinding(ctx, tx, u); err != nil {
		return err
	}
	_, err = tx.Exec(ctx, "UPDATE customer_proxy SET state='none',updated_at=$2 WHERE customer_id=$1", customerID, s.now())
	return err
}

func (s *store) expireSubscriptions(ctx context.Context) error {
	return s.write(ctx, func(tx pgx.Tx) error {
		rows, err := tx.Query(ctx, `UPDATE subscriptions SET status='cancelled',updated_at=$1 WHERE status='past_due' AND current_period_end + COALESCE((SELECT value::double precision FROM settings WHERE key='subscription_grace_seconds'),259200) <= $1 RETURNING id`, s.now())
		if err != nil {
			return err
		}
		ids, err := pgx.CollectRows(rows, pgx.RowTo[int64])
		if err != nil {
			return err
		}
		for _, id := range ids {
			if err := s.deprovisionSubscription(ctx, tx, id); err != nil {
				return err
			}
		}
		_, err = tx.Exec(ctx, `UPDATE subscriptions SET status='expired',updated_at=$1 WHERE status='pending' AND created_at + 86400 <= $1`, s.now())
		return err
	})
}

func (s *store) runSubscriptionExpiry(ctx context.Context) {
	ticker := time.NewTicker(time.Minute)
	defer ticker.Stop()
	for {
		if err := s.expireSubscriptions(ctx); err != nil && !errors.Is(err, context.Canceled) {
			log.Printf("expire subscriptions: %v", err)
		}
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
		}
	}
}
