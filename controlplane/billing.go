func (s *store) plans(ctx context.Context) ([]planView, error) {
	return rowsOf[planView](ctx, s.pool, `SELECT code,name,price_cny,currency,interval,true AS includes_ip,fulfillment='manual' AS team_seat,stripe_price_id,active,sort FROM plans ORDER BY sort,code`)
}
func (s *store) updatePlans(ctx context.Context, plans []planView) error {
	return s.write(ctx, func(tx pgx.Tx) error {
		for _, p := range plans {
			if p.Amount < 1 || p.Name == "" {
				return failure(400, "invalid plan")
			}
			tag, err := tx.Exec(ctx, `UPDATE plans SET name=$2,price_cny=$3,stripe_price_id=$4,active=$5,sort=$6 WHERE code=$1`, p.Code, p.Name, p.Amount, p.StripePriceID, p.Active, p.Sort)
			if err != nil || tag.RowsAffected() != 1 {
				return fmt.Errorf("update plan %s: %w", p.Code, err)
			}
		}
		return nil
	})
}

func (s *store) customerEntitlement(ctx context.Context, customerID int64) (*subscriptionView, any, error) {
	sub, err := rowOf[subscriptionView](ctx, s.pool, `SELECT s.id,s.plan_code AS plan,s.status,s.current_period_start,s.current_period_end,s.cancel_at_period_end,
	(SELECT status FROM provisioning WHERE subscription_id=s.id AND kind='team_seat' ORDER BY id DESC LIMIT 1) AS team_seat
	FROM subscriptions s WHERE s.customer_id=$1 ORDER BY s.updated_at DESC LIMIT 1`, customerID)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, nil, nil
	}
	if err != nil {
		return nil, nil, err
	}
	var proxy proxyView
	err = s.pool.QueryRow(ctx, `SELECT cp.state,host(u.egress_ip) AS egress_ip FROM customer_proxy cp JOIN users u ON u.name=cp.user_name WHERE cp.customer_id=$1`, customerID).Scan(&proxy.State, &proxy.EgressIP)
	if errors.Is(err, pgx.ErrNoRows) {
		sub.Proxy = map[string]any{"state": "none"}
		return &sub, nil, nil
	}
	if err != nil {
		return nil, nil, err
	}
	sub.Proxy = proxy
	return &sub, proxy, nil
}
func (s *store) currentSubscription(ctx context.Context, customerID int64) (*subscriptionView, error) {
	sub, _, err := s.customerEntitlement(ctx, customerID)
	return sub, err
}
