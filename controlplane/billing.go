func (a *api) adminCustomerUpdate(r *apiRequest) (response, error) {
	var body struct {
		Status string `json:"status"`
	}
	if err := r.decode(&body, "status"); err != nil {
		return response{}, err
	}
	id, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
	if err != nil {
		return response{}, failure(400, "invalid customer id")
	}
	if body.Status != "active" && body.Status != "suspended" {
		return response{}, failure(400, "invalid status")
	}
	err = a.store.write(r.Context(), func(tx pgx.Tx) error {
		_, err := tx.Exec(r.Context(), "UPDATE customers SET status=$2 WHERE id=$1", id, body.Status)
		if err != nil {
			return err
		}
		if body.Status == "suspended" {
			_, err = tx.Exec(r.Context(), `UPDATE devices SET revoked_at=$2 WHERE user_name=(SELECT user_name FROM customer_proxy WHERE customer_id=$1) AND revoked_at IS NULL`, id, a.store.now())
		}
		return err
	})
	return ok(object{"id": id, "status": body.Status}, err)
}
