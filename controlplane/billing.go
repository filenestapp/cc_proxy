func (a *api) accountCheckout(r *apiRequest) (response, error) {
	if a.stripe == nil {
		return response{}, failureCode(503, "stripe_unavailable", "Stripe is not configured")
	}
	var body struct {
		Plan string `json:"plan"`
	}
	if err := r.decode(&body, "plan"); err != nil {
		return response{}, err
	}
	c, err := a.store.customerByID(r.Context(), r.Customer.CustomerID)
	if err != nil {
		return response{}, err
	}
	if !c.EmailVerified {
		return response{}, failureCode(403, "email_unverified", "email is not verified")
	}
	sub, err := a.store.currentSubscription(r.Context(), c.ID)
	if err != nil {
		return response{}, err
	}
	if sub != nil && (sub.Status == "pending" || sub.Status == "active" || sub.Status == "past_due") {
		return response{}, failureCode(409, "subscription_exists", "subscription already exists")
	}
	var price string
	err = a.store.pool.QueryRow(r.Context(), "SELECT stripe_price_id FROM plans WHERE code=$1 AND active", body.Plan).Scan(&price)
	if errors.Is(err, pgx.ErrNoRows) {
		return response{}, failure(404, "plan not found")
	}
	if err != nil {
		return response{}, err
	}
	if price == "" {
		return response{}, failureCode(503, "stripe_unavailable", "plan is not configured in Stripe")
	}
	stripeCustomer, err := a.store.customerStripeID(r.Context(), c.ID)
	if err != nil {
		return response{}, err
	}
	if stripeCustomer == "" {
		stripeCustomer, err = a.stripe.createCustomer(r.Context(), c.Email)
		if err != nil {
			return response{}, err
		}
		if err = a.store.setCustomerStripeID(r.Context(), c.ID, stripeCustomer); err != nil {
			return response{}, err
		}
	}
	u, err := a.stripe.createCheckout(r.Context(), stripeCustomer, price, body.Plan, c.ID, "https://app.aifree.sg/account?checkout=success", "https://app.aifree.sg/account?checkout=cancel")
	return ok(object{"url": u}, err)
}
