CREATE TABLE IF NOT EXISTS settings (
    key text PRIMARY KEY,
    value jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS hosts (
    name text COLLATE "C" PRIMARY KEY,
    public_host text NOT NULL,
    observed_public_ipv4 inet CHECK (family(observed_public_ipv4) = 4 AND masklen(observed_public_ipv4) = 32),
    port_min integer NOT NULL,
    port_max integer NOT NULL,
    reality_private text NOT NULL,
    reality_public text NOT NULL,
    short_id text NOT NULL,
    server_name text NOT NULL,
    handshake_server text NOT NULL,
    handshake_port integer NOT NULL DEFAULT 443,
    block_private boolean NOT NULL DEFAULT true,
    block_cidrs jsonb NOT NULL DEFAULT '["169.254.169.254/32"]',
    agent_token_hash text NOT NULL UNIQUE,
    created_at double precision NOT NULL,
    CHECK (port_min BETWEEN 1 AND port_max AND port_max <= 65535)
);

CREATE TABLE IF NOT EXISTS egress_ips (
    ip inet PRIMARY KEY CHECK (family(ip) = 4 AND masklen(ip) = 32),
    host text COLLATE "C" NOT NULL REFERENCES hosts(name),
    banned boolean NOT NULL DEFAULT false,
    cooldown_until double precision NOT NULL DEFAULT 0,
    note text NOT NULL DEFAULT '',
    UNIQUE (ip, host)
);
CREATE INDEX IF NOT EXISTS egress_ips_host ON egress_ips(host, ip);

CREATE TABLE IF NOT EXISTS users (
    name text COLLATE "C" PRIMARY KEY,
    password_hash text NOT NULL,
    mode text NOT NULL DEFAULT 'exclusive' CHECK (mode IN ('exclusive', 'shared')),
    egress_ip inet,
    host text COLLATE "C",
    port integer CHECK (port BETWEEN 1 AND 65535),
    max_devices integer NOT NULL DEFAULT 5 CHECK (max_devices >= 1),
    created_at double precision NOT NULL,
    CHECK ((egress_ip IS NULL) = (port IS NULL)),
    FOREIGN KEY (egress_ip, host) REFERENCES egress_ips(ip, host) MATCH FULL,
    UNIQUE (host, port)
);
CREATE INDEX IF NOT EXISTS users_egress_ip ON users(egress_ip);

CREATE TABLE IF NOT EXISTS devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name text COLLATE "C" NOT NULL REFERENCES users(name) ON DELETE CASCADE,
    name text COLLATE "C" NOT NULL,
    platform text NOT NULL DEFAULT '',
    uuid uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    token_hash text NOT NULL UNIQUE,
    revoked_at double precision,
    last_seen double precision,
    created_at double precision NOT NULL,
    UNIQUE (user_name, name)
);

CREATE TABLE IF NOT EXISTS admins (
    name text COLLATE "C" PRIMARY KEY,
    password_hash text NOT NULL,
    created_at double precision NOT NULL,
    last_login double precision
);

CREATE TABLE IF NOT EXISTS admin_sessions (
    token_hash text PRIMARY KEY,
    admin text NOT NULL REFERENCES admins(name) ON DELETE CASCADE,
    csrf text NOT NULL,
    created_at double precision NOT NULL,
    expires_at double precision NOT NULL,
    address text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS admin_sessions_admin ON admin_sessions(admin);

CREATE TABLE IF NOT EXISTS customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text COLLATE "C" NOT NULL UNIQUE,
    password_hash text NOT NULL,
    email_verified_at double precision,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    locale text NOT NULL DEFAULT '',
    created_at double precision NOT NULL,
    stripe_customer_id text UNIQUE
);

CREATE TABLE IF NOT EXISTS customer_sessions (
    token_hash text PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    csrf text NOT NULL,
    created_at double precision NOT NULL,
    expires_at double precision NOT NULL,
    address text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS customer_sessions_customer ON customer_sessions(customer_id);

CREATE TABLE IF NOT EXISTS email_tokens (
    token_hash text PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    purpose text NOT NULL CHECK (purpose IN ('verify', 'reset')),
    created_at double precision NOT NULL,
    expires_at double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS email_tokens_customer_purpose ON email_tokens(customer_id, purpose);

CREATE TABLE IF NOT EXISTS audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at double precision NOT NULL,
    actor text NOT NULL,
    action text NOT NULL,
    target text NOT NULL DEFAULT '',
    detail text NOT NULL DEFAULT '',
    address text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS audit_at ON audit(at);

CREATE TABLE IF NOT EXISTS agents (
    name text COLLATE "C" PRIMARY KEY,
    last_seen double precision NOT NULL,
    config_etag text,
    singbox_running boolean,
    apply_error text,
    apply_state text CHECK (apply_state IN ('confirmed', 'pending', 'failed', 'unknown'))
);

CREATE TABLE IF NOT EXISTS probes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('egress', 'entry')),
    subject text NOT NULL,
    source text COLLATE "C" NOT NULL,
    target text COLLATE "C" NOT NULL,
    ok boolean NOT NULL,
    latency_ms double precision,
    detail text NOT NULL DEFAULT '',
    at double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS probes_lookup ON probes(kind, subject, source, target, at DESC, id DESC);
CREATE INDEX IF NOT EXISTS probes_at ON probes(at);

CREATE TABLE IF NOT EXISTS alerts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key text NOT NULL,
    rule text NOT NULL,
    subject text NOT NULL,
    severity text NOT NULL,
    summary text NOT NULL,
    state text NOT NULL CHECK (state IN ('pending', 'firing', 'resolved')),
    started_at double precision NOT NULL,
    fired_at double precision,
    resolved_at double precision,
    notify text,
    notified_at double precision,
    notify_error text
);
CREATE UNIQUE INDEX IF NOT EXISTS alerts_active ON alerts(key) WHERE state != 'resolved';

