const (
	customerSessionTTL    = 30 * 24 * time.Hour
	customerSessionMaxTTL = 90 * 24 * time.Hour
	verificationTokenTTL  = 24 * time.Hour
	resetTokenTTL         = time.Hour
	accountActionWindow   = time.Hour
	mailSendTimeout       = 15 * time.Second
)

const customerSchemaSQL = `
CREATE TABLE IF NOT EXISTS customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text COLLATE "C" NOT NULL UNIQUE,
    password_hash text NOT NULL,
    email_verified_at double precision,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    locale text NOT NULL DEFAULT '',
    created_at double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS customer_sessions (
    token_hash text PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    csrf text NOT NULL,
    created_at double precision NOT NULL,
    expires_at double precision NOT NULL,
    address text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS customer_sessions_customer ON customer_sessions(customer_id);
CREATE TABLE IF NOT EXISTS email_tokens (
    token_hash text PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
    purpose text NOT NULL CHECK (purpose IN ('verify', 'reset')),
    created_at double precision NOT NULL,
    expires_at double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS email_tokens_customer_purpose ON email_tokens(customer_id, purpose);
`

func ensureCustomerTables(ctx context.Context, db database) error {
	_, err := db.Exec(ctx, customerSchemaSQL)
	return err
}

type accountActionLimiter struct {
	mu   sync.Mutex
	hits map[string][]time.Time
}

func (l *accountActionLimiter) allowedEmail(now time.Time, action, email, address string) bool {
	l.mu.Lock()
	defer l.mu.Unlock()
	cutoff := now.Add(-accountActionWindow)
	for key, hits := range l.hits {
		i := 0
		for i < len(hits) && !hits[i].After(cutoff) {
			i++
		}
		if i == len(hits) {
			delete(l.hits, key)
			continue
		}
		l.hits[key] = hits[i:]
	}
	keys := []struct {
		key string
		max int
	}{
		{action + ":email:" + email, 3},
		{action + ":addr:" + address, 5},
	}
	for _, key := range keys {
		hits := l.hits[key.key]
		if len(hits) >= key.max {
			return false
		}
		l.hits[key.key] = append(hits, now)
	}
	return true
}

type customer struct {
	ID            int64   `json:"id"`
	Email         string  `json:"email"`
	EmailVerified bool    `json:"email_verified"`
	Status        string  `json:"status"`
	Locale        string  `json:"locale"`
	CreatedAt     float64 `db:"created_at" json:"created_at"`
}

type customerSession struct {
	CustomerID int64
	CSRF       string
	CreatedAt  float64
	ExpiresAt  float64
}

func normalizeEmail(value string) (string, error) {
	email := strings.ToLower(strings.TrimSpace(value))
	parsed, err := mail.ParseAddress(email)
	if err != nil || parsed.Address != email || !strings.Contains(email, "@") {
		return "", failureCode(400, "invalid_email", "invalid email address")
	}
	return email, nil
}

func customerPassword(password string) (string, error) {
	if err := checkPasswordPolicy(password); err != nil {
		return "", failureCode(400, "weak_password", "password must be at least 8 characters")
	}
	return hashPassword(password), nil
}

func invalidCredentials() error {
	return failureCode(401, "invalid_credentials", "invalid credentials")
}

func issueEmailToken(ctx context.Context, tx pgx.Tx, customerID int64, purpose string, now float64, ttl time.Duration) (string, error) {
	if _, err := tx.Exec(ctx, "DELETE FROM email_tokens WHERE customer_id = $1 AND purpose = $2", customerID, purpose); err != nil {
		return "", err
	}
	token := randomToken(32)
	_, err := tx.Exec(ctx, `INSERT INTO email_tokens(token_hash, customer_id, purpose, created_at, expires_at)
		VALUES ($1,$2,$3,$4,$5)`, hashToken(token), customerID, purpose, now, now+ttl.Seconds())
	return token, err
}

func issueCustomerSession(ctx context.Context, tx pgx.Tx, customerID int64, address string, now float64) (string, string, error) {
	token, csrf := randomToken(32), randomToken(24)
	if _, err := tx.Exec(ctx, "DELETE FROM customer_sessions WHERE expires_at <= $1", now); err != nil {
		return "", "", err
	}
	_, err := tx.Exec(ctx, `INSERT INTO customer_sessions(token_hash, customer_id, csrf, created_at, expires_at, address)
		VALUES ($1,$2,$3,$4,$5,$6)`, hashToken(token), customerID, csrf, now, now+customerSessionTTL.Seconds(), address)
	return token, csrf, err
}

func (s *store) registerCustomer(ctx context.Context, email, password, locale, address string) (customer, string, string, string, error) {
	email, err := normalizeEmail(email)
	if err != nil {
		return customer{}, "", "", "", err
	}
	hash, err := customerPassword(password)
	if err != nil {
		return customer{}, "", "", "", err
	}
	var result customer
	var session, csrf, verification string
	err = s.write(ctx, func(tx pgx.Tx) error {
		now := s.now()
		err := tx.QueryRow(ctx, `INSERT INTO customers(email, password_hash, locale, created_at)
			VALUES ($1,$2,$3,$4) RETURNING id, email, email_verified_at IS NOT NULL AS email_verified, status, locale, created_at`,
			email, hash, strings.TrimSpace(locale), now).Scan(&result.ID, &result.Email, &result.EmailVerified, &result.Status, &result.Locale, &result.CreatedAt)
		if uniqueViolation(err) {
			return failureCode(409, "email_taken", "email is already registered")
		}
		if err != nil {
			return err
		}
		verification, err = issueEmailToken(ctx, tx, result.ID, "verify", now, verificationTokenTTL)
		if err != nil {
			return err
		}
		session, csrf, err = issueCustomerSession(ctx, tx, result.ID, address, now)
		return err
	})
	return result, session, csrf, verification, err
}

func (s *store) customerByID(ctx context.Context, id int64) (customer, error) {
	return rowOf[customer](ctx, s.pool, `SELECT id, email, email_verified_at IS NOT NULL AS email_verified,
		status, locale, created_at FROM customers WHERE id = $1`, id)
}

func (s *store) checkCustomerCredentials(ctx context.Context, email, password string) (customer, error) {
	email = strings.ToLower(strings.TrimSpace(email))
	var stored string
	var result customer
	err := s.pool.QueryRow(ctx, `SELECT id, email, password_hash, email_verified_at IS NOT NULL AS email_verified,
		status, locale, created_at FROM customers WHERE email = $1`, email).Scan(
		&result.ID, &result.Email, &stored, &result.EmailVerified, &result.Status, &result.Locale, &result.CreatedAt)
	if errors.Is(err, pgx.ErrNoRows) {
		checkPassword(password, dummyPasswordHash)
		return customer{}, invalidCredentials()
	}
	if err != nil {
		return customer{}, err
	}
	if !checkPassword(password, stored) {
		return customer{}, invalidCredentials()
	}
	if result.Status == "suspended" {
		return customer{}, failureCode(403, "suspended", "customer account is suspended")
	}
	return result, nil
}

func (s *store) loginCustomer(ctx context.Context, email, password, address string) (customer, string, string, error) {
	result, err := s.checkCustomerCredentials(ctx, email, password)
	if err != nil {
		return customer{}, "", "", err
	}
	var token, csrf string
	err = s.write(ctx, func(tx pgx.Tx) error {
		now := s.now()
		var current string
		err := tx.QueryRow(ctx, "SELECT password_hash FROM customers WHERE id = $1 AND status = 'active'", result.ID).Scan(&current)
		if errors.Is(err, pgx.ErrNoRows) || (err == nil && current != "" && !checkPassword(password, current)) {
			return invalidCredentials()
		}
		if err != nil {
			return err
		}
		token, csrf, err = issueCustomerSession(ctx, tx, result.ID, address, now)
		return err
	})
	return result, token, csrf, err
}

func (s *store) customerSession(ctx context.Context, token string) (customerSession, error) {
	return rowOf[customerSession](ctx, s.pool, `SELECT cs.customer_id, cs.csrf, cs.created_at, cs.expires_at
		FROM customer_sessions cs JOIN customers c ON c.id = cs.customer_id
		WHERE cs.token_hash = $1 AND cs.expires_at > $2 AND c.status = 'active'`, hashToken(token), s.now())
}

func (s *store) touchCustomerSession(ctx context.Context, token string) error {
	now := s.now()
	_, err := s.pool.Exec(ctx, `UPDATE customer_sessions SET expires_at = LEAST(created_at + $2, $1 + $3)
		WHERE token_hash = $4 AND expires_at > $1`, now, customerSessionMaxTTL.Seconds(), customerSessionTTL.Seconds(), hashToken(token))
	return err
}

func (s *store) logoutCustomer(ctx context.Context, token string) error {
	_, err := s.pool.Exec(ctx, "DELETE FROM customer_sessions WHERE token_hash = $1", hashToken(token))
	return err
}

func (s *store) resendVerification(ctx context.Context, customerID int64) (customer, string, error) {
	var result customer
	var token string
	err := s.write(ctx, func(tx pgx.Tx) error {
		var verified bool
		var err error
		result, err = s.customerByID(ctx, customerID)
		if err != nil {
			return err
		}
		verified = result.EmailVerified
		if verified {
			return failureCode(409, "already_verified", "email is already verified")
		}
		token, err = issueEmailToken(ctx, tx, customerID, "verify", s.now(), verificationTokenTTL)
		return err
	})
	return result, token, err
}

func (s *store) verifyCustomerEmail(ctx context.Context, token string) (customer, error) {
	var result customer
	err := s.write(ctx, func(tx pgx.Tx) error {
		now := s.now()
		var customerID int64
		err := tx.QueryRow(ctx, `DELETE FROM email_tokens WHERE token_hash = $1 AND purpose = 'verify' AND expires_at > $2
			RETURNING customer_id`, hashToken(token), now).Scan(&customerID)
		if errors.Is(err, pgx.ErrNoRows) {
			return failureCode(400, "invalid_token", "invalid or expired token")
		}
		if err != nil {
			return err
		}
		if _, err := tx.Exec(ctx, "UPDATE customers SET email_verified_at = COALESCE(email_verified_at, $2) WHERE id = $1", customerID, now); err != nil {
			return err
		}
		result, err = rowOf[customer](ctx, tx, `SELECT id, email, email_verified_at IS NOT NULL AS email_verified,
			status, locale, created_at FROM customers WHERE id = $1`, customerID)
		return err
	})
	return result, err
}

func (s *store) issuePasswordReset(ctx context.Context, email string) (string, error) {
	email, err := normalizeEmail(email)
	if err != nil {
		return "", err
	}
	var token string
	err = s.write(ctx, func(tx pgx.Tx) error {
		var customerID int64
		err := tx.QueryRow(ctx, "SELECT id FROM customers WHERE email = $1", email).Scan(&customerID)
		if errors.Is(err, pgx.ErrNoRows) {
			return nil
		}
		if err != nil {
			return err
		}
		token, err = issueEmailToken(ctx, tx, customerID, "reset", s.now(), resetTokenTTL)
		return err
	})
	return token, err
}

func (s *store) changeCustomerPassword(ctx context.Context, customerID int64, current, next, keepToken string) error {
	hash, err := customerPassword(next)
	if err != nil {
		return err
	}
	return s.write(ctx, func(tx pgx.Tx) error {
		var stored string
		err := tx.QueryRow(ctx, "SELECT password_hash FROM customers WHERE id = $1", customerID).Scan(&stored)
		if errors.Is(err, pgx.ErrNoRows) || (err == nil && !checkPassword(current, stored)) {
			return invalidCredentials()
		}
		if err != nil {
			return err
		}
		if _, err := tx.Exec(ctx, "UPDATE customers SET password_hash = $2 WHERE id = $1", customerID, hash); err != nil {
			return err
		}
		_, err = tx.Exec(ctx, "DELETE FROM customer_sessions WHERE customer_id = $1 AND token_hash != $2", customerID, hashToken(keepToken))
		return err
	})
}

func (s *store) resetCustomerPassword(ctx context.Context, token, next string) error {
	hash, err := customerPassword(next)
	if err != nil {
		return err
	}
	return s.write(ctx, func(tx pgx.Tx) error {
		var customerID int64
		now := s.now()
		err := tx.QueryRow(ctx, `DELETE FROM email_tokens WHERE token_hash = $1 AND purpose = 'reset' AND expires_at > $2
			RETURNING customer_id`, hashToken(token), now).Scan(&customerID)
		if errors.Is(err, pgx.ErrNoRows) {
			return failureCode(400, "invalid_token", "invalid or expired token")
		}
		if err != nil {
			return err
		}
		if _, err := tx.Exec(ctx, "UPDATE customers SET password_hash = $2 WHERE id = $1", customerID, hash); err != nil {
			return err
		}
		_, err = tx.Exec(ctx, "DELETE FROM customer_sessions WHERE customer_id = $1", customerID)
		return err
	})
}

func (a *api) accountRoutes() {
	a.bind("POST /v1/account/register", "", "", a.accountRegister)
	a.bind("POST /v1/account/verify", "", "", a.accountVerify)
	a.bind("POST /v1/account/verify/resend", "customer", "", a.accountVerifyResend)
	a.bind("POST /v1/account/login", "", "", a.accountLogin)
	a.bind("POST /v1/account/logout", "customer", "", a.accountLogout)
	a.bind("GET /v1/account/me", "customer", "", a.accountMe)
	a.bind("POST /v1/account/password", "customer", "", a.accountPassword)
	a.bind("POST /v1/account/password/forgot", "", "", a.accountPasswordForgot)
	a.bind("POST /v1/account/password/reset", "", "", a.accountPasswordReset)
}

func (a *api) accountRateLimit(action, email, address string) error {
	if !a.actions.allowedEmail(a.store.clock(), action, email, address) {
		return failureCode(429, "rate_limited", "too many requests; try again later")
	}
	return nil
}

func (a *api) sendVerification(email, token string) {
	a.sendMail(email, "Verify your aifree email", "https://app.aifree.sg/account/verify?token="+token, "verification")
}

func (a *api) sendPasswordReset(email, token string) {
	if token == "" {
		return
	}
	a.sendMail(email, "Reset your aifree password", "https://app.aifree.sg/account/reset?token="+token, "password reset")
}

func (a *api) sendMail(email, subject, content, purpose string) {
	if a.mail == nil {
		log.Printf("%s email for %s was not sent: cloud-mail is not configured", purpose, email)
		return
	}
	go func() {
		ctx, cancel := context.WithTimeout(context.Background(), mailSendTimeout)
		defer cancel()
		if err := a.mail.send(ctx, email, subject, content); err != nil {
			log.Printf("send %s email: %v", purpose, err)
		}
	}()
}

func (a *api) accountRegister(r *apiRequest) (response, error) {
	var body struct {
		Email    string `json:"email"`
		Password string `json:"password"`
		Locale   string `json:"locale"`
	}
	if err := r.decode(&body, "email", "password"); err != nil {
		return response{}, err
	}
	email, err := normalizeEmail(body.Email)
	if err != nil {
		return response{}, err
	}
	if err := a.accountRateLimit("register", email, r.Address); err != nil {
		return response{}, err
	}
	result, session, _, verification, err := a.store.registerCustomer(r.Context(), email, body.Password, body.Locale, r.Address)
	if err != nil {
		return response{}, err
	}
	a.sendVerification(result.Email, verification)
	return response{status: 201, body: object{"customer": result},
		cookie: a.customerCookie(r, session, int(customerSessionTTL.Seconds()))}, nil
}

func (a *api) accountVerify(r *apiRequest) (response, error) {
	var body struct {
		Token string `json:"token"`
	}
	if err := r.decode(&body, "token"); err != nil {
		return response{}, err
	}
	customer, err := a.store.verifyCustomerEmail(r.Context(), body.Token)
	return ok(object{"customer": customer}, err)
}

func (a *api) accountVerifyResend(r *apiRequest) (response, error) {
	customer, err := a.store.customerByID(r.Context(), r.Customer.CustomerID)
	if err != nil {
		return response{}, err
	}
	if err := a.accountRateLimit("verify_resend", customer.Email, r.Address); err != nil {
		return response{}, err
	}
	_, token, err := a.store.resendVerification(r.Context(), customer.ID)
	if err != nil {
		return response{}, err
	}
	a.sendVerification(customer.Email, token)
	return ok(object{"customer": customer}, nil)
}

func (a *api) accountLogin(r *apiRequest) (response, error) {
	var body struct {
		Email    string `json:"email"`
		Password string `json:"password"`
	}
	if err := r.decode(&body, "email", "password"); err != nil {
		return response{}, err
	}
	email := strings.ToLower(strings.TrimSpace(body.Email))
	keys := []string{"customer:" + email, "addr:" + r.Address}
	if a.limiter.blocked(a.store.clock(), keys...) {
		return response{}, failureCode(429, "rate_limited", "too many failed sign-ins; try again later")
	}
	customer, token, csrf, err := a.store.loginCustomer(r.Context(), email, body.Password, r.Address)
	if err != nil && statusOf(err) == 401 {
		a.limiter.fail(a.store.clock(), keys...)
	}
	if err != nil {
		return response{}, err
	}
	return response{status: 200, body: object{"customer": customer, "csrf": csrf}, cookie: a.customerCookie(r, token, int(customerSessionTTL.Seconds()))}, nil
}

func (a *api) accountLogout(r *apiRequest) (response, error) {
	err := a.store.logoutCustomer(r.Context(), customerCookieValue(r.Request))
	return response{status: 204, cookie: a.customerCookie(r, "", -1)}, err
}

func (a *api) accountMe(r *apiRequest) (response, error) {
	customer, err := a.store.customerByID(r.Context(), r.Customer.CustomerID)
	if err != nil {
		return response{}, err
	}
	return ok(object{"customer": customer, "csrf": r.Customer.CSRF, "subscription": nil, "proxy": nil, "mailbox": nil}, nil)
}

func (a *api) accountPassword(r *apiRequest) (response, error) {
	var body struct {
		Current string `json:"current_password"`
		Next    string `json:"new_password"`
	}
	if err := r.decode(&body, "current_password", "new_password"); err != nil {
		return response{}, err
	}
	err := a.store.changeCustomerPassword(r.Context(), r.Customer.CustomerID, body.Current, body.Next, customerCookieValue(r.Request))
	return response{status: 204}, err
}

func (a *api) accountPasswordForgot(r *apiRequest) (response, error) {
	var body struct {
		Email string `json:"email"`
	}
	if err := r.decode(&body, "email"); err != nil {
		return response{}, err
	}
	email, err := normalizeEmail(body.Email)
	if err != nil {
		return response{}, err
	}
	if err := a.accountRateLimit("password_forgot", email, r.Address); err != nil {
		return response{}, err
	}
	token, err := a.store.issuePasswordReset(r.Context(), email)
	if err != nil {
		return response{}, err
	}
	a.sendPasswordReset(email, token)
	return response{status: 202, body: object{}}, nil
}

func (a *api) accountPasswordReset(r *apiRequest) (response, error) {
	var body struct {
		Token string `json:"token"`
		Next  string `json:"new_password"`
	}
	if err := r.decode(&body, "token", "new_password"); err != nil {
		return response{}, err
	}
	return response{status: 204}, a.store.resetCustomerPassword(r.Context(), body.Token, body.Next)
}
